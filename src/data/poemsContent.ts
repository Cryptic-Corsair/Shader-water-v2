export async function getPoemBySlug(slug: string): Promise<PoemFull | null> {
  const meta = POEMS_CATALOG.find((poem) => poem.slug === slug);
  if (!meta) {
    return null;
  }

  const body = POEM_BODIES[slug];
  if (!body) {
    return null;
  }

  return {
    ...meta,
    epigraph: body.epigraph,
    stanzas: body.stanzas,
    marginalia: body.marginalia,
  };
}

export function getAdjacentPoems(slug: string): {
  prev: (typeof POEMS_CATALOG)[number] | null;
  next: (typeof POEMS_CATALOG)[number] | null;
} {
  const sorted = [...POEMS_CATALOG].sort((a, b) => a.order - b.order);
  const idx = sorted.findIndex((p) => p.slug === slug);
  if (idx === -1) {
    return { prev: null, next: null };
  }
  return {
    prev: idx > 0 ? sorted[idx - 1] : null,
    next: idx < sorted.length - 1 ? sorted[idx + 1] : null,
  };
}

export function getReadingRoomAdjacentPoems(slug: string): {
  prev: (typeof POEMS_CATALOG)[number] | null;
  next: (typeof POEMS_CATALOG)[number] | null;
} {
  const current = POEMS_CATALOG.find((p) => p.slug === slug);
  if (!current || POEMS_CATALOG.length <= 1) {
    return { prev: null, next: null };
  }

  const sameCollection = POEMS_CATALOG.filter(
    (p) => p.collection === current.collection
  ).sort((a, b) => a.order - b.order);
  const otherPoems = POEMS_CATALOG.filter(
    (p) => p.collection !== current.collection
  ).sort((a, b) => a.order - b.order);

  const ring = [...sameCollection, ...otherPoems];
  const idx = ring.findIndex((p) => p.slug === slug);
  if (idx === -1) {
    return { prev: null, next: null };
  }

  return {
    prev: ring[(idx - 1 + ring.length) % ring.length],
    next: ring[(idx + 1) % ring.length],
  };
}

export function getPoemBodyText(slug: string): string {
  const body = POEM_BODIES[slug];
  if (!body) return '';
  return body.stanzas.flat().join(' ');
}

export function getPoemOpeningStanza(slug: string, maxLines = 3): string[] {
  const body = POEM_BODIES[slug];
  if (!body || body.stanzas.length === 0) return [];
  const allLines = body.stanzas.flat();
  const firstStanza = body.stanzas[0];
  const source = firstStanza.length >= 2 ? firstStanza : allLines;
  return source.slice(0, Math.max(1, maxLines));
}

